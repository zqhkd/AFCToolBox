/**
  * @brief This function handles USART2 global interrupt.
  */
void USART2_IRQHandler(void)
{
  /* USER CODE BEGIN USART2_IRQn 0 */
  // 核心修改1：先处理RX中断，再置位TC标志，避免RX操作清除TC
  // 核心修改2：仅在TXE（TX FIFO空）且TC（发送完成）同时满足时置位
  if(__HAL_UART_GET_FLAG(&huart2,UART_FLAG_TXE)) {
    g_bDtComOutSucessful = true;
//    __HAL_UART_CLEAR_FLAG(&huart2,UART_FLAG_TC); // 手动清除TC，避免重复触发
  }
  /* USER CODE END USART2_IRQn 0 */
  HAL_UART_IRQHandler(&huart2);
  /* USER CODE BEGIN USART2_IRQn 1 */
//	if(__HAL_UART_GET_FLAG(&huart2,UART_FLAG_RXNE)) ProDtComRcvIRQ();
	ProDtComRcvIRQ();
  /* USER CODE END USART2_IRQn 1 */
}

